import test from 'node:test';
import assert from 'node:assert/strict';
import items from '../../content/econ-drafts/development-economics.json' with {type:'json'};
const key=suffix=>items.find(q=>q.id===`development-economics-u${suffix}`).correct;
test('development keys satisfy poverty, risk, allocation and identification calculations',()=>{
 const headcount=xs=>xs.filter(x=>x<100).length/xs.length;
 const gap=(xs,power=1)=>xs.reduce((sum,x)=>sum+(Math.max(100-x,0)/100)**power,0)/xs.length;
 assert.equal(key('1-01'),`${100*headcount([40,60,90,110,200])}%.`);
 assert.equal(key('1-02'),`${gap([40,80,120,160]).toFixed(2)}.`);
 const before=[20,80,150],after=[40,60,150];
 assert.equal(headcount(before),headcount(after));assert.equal(gap(before),gap(after));assert.ok(gap(after,2)<gap(before,2));
 assert.equal(key('1-07'),`A, at ${300/2} per person versus B at ${500/5}.`);
 assert.equal(key('2-02'),`${100-80}.`);
 let assets=0;for(let t=0;t<150;t++)assets=20+.8*assets;assert.ok(Math.abs(assets-100)<1e-10);
 assert.equal(key('2-04'),`${100/.8}.`);
 assert.equal(key('2-09'),`${((Math.sqrt(100)+Math.sqrt(400))/2)**2}.`);
 assert.equal(key('3-03'),`An increase of ${20*2-30}.`);
 assert.equal(key('3-09'),`It rises from ${10-3} to ${10-1}.`);
 const payoff=(own,other)=>own?(other?70-40:-40):0;
 assert.ok(payoff(true,true)>payoff(false,true));assert.ok(payoff(false,false)>payoff(true,false));
 const mixedProbability=40/70;assert.ok(Math.abs(mixedProbability*30+(1-mixedProbability)*(-40))<1e-12);
 assert.match(items.find(q=>q.id.endsWith('u3-10')).explanation,/pure-strategy/);
 assert.equal(key('4-02'),`${450-100-300}.`);
 assert.ok(150/40<100/20);assert.equal(key('4-10'),'B, because it prevents 40 episodes within budget.');
 assert.equal(key('5-01'),`Yes; expected net urban income is ${.7*100-5}, above 60.`);
 assert.equal(key('5-03'),`It rises by about ${Math.round((.5*200-.7*100)/(.7*100)*100)}%.`);
 assert.equal(key('5-04'),`It rises from ${.75*2+.25*6} to ${.5*2+.5*6}.`);
 assert.equal(key('6-02'),`${120-100} earnings units.`);
 assert.equal(key('6-03'),`${Math.round(12/(.6-.2))} earnings units for people induced to participate by the offer.`);
 assert.equal(key('6-05'),`${(70-50)-(55-40)}.`);
 assert.equal(key('6-08'),`${(40/100).toFixed(2)}.`);
});
