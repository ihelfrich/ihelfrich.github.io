import test from 'node:test';
import assert from 'node:assert/strict';
import items from '../../content/econ-drafts/international-trade.json' with {type:'json'};
const key=suffix=>items.find(q=>q.id===`international-trade-u${suffix}`).correct;
test('reviewed trade keys satisfy the stated cost, allocation and policy calculations',()=>{
 assert.ok(2/6<4/8);assert.ok(2<3&&3<5);
 assert.equal(key('1-03'),`Bicycles only, with a $${18/3} wage.`);assert.ok(18/3>8/2);
 assert.equal(key('1-04'),`${120/2-20} fish and ${20/1} jars of honey.`);
 assert.equal(key('1-06'),`Foreign production, at $${9/3} per usable crate versus $${(12/6)/.5} for imports.`);
 assert.equal(key('1-08'),`${50*(10-8)} units.`);
 assert.ok(1.04/1.10<1&&1.04>1);
 const laborA=(100-80+100)/2;assert.equal(key('2-05'),`${laborA} workers in A and ${100-laborA} in B.`);
 assert.ok(Math.abs(1.10/Math.sqrt(1.21)-1)<1e-12);
 assert.equal(key('3-01'),`North, because its capital-labor ratio is ${300/100} rather than ${500/250}.`);
 const rental=(2*15-10)/5,wage=(10-rental)/2;assert.equal(key('3-05'),`w=$${wage} and r=$${rental}.`);
 assert.equal(key('3-08'),`Exports ${10*4-20*1} capital units and imports ${20*2-10*1} labor units.`);
 assert.equal(key('4-01'),`It falls from $${600/30+20} to $${600/60+20}.`);
 assert.equal(key('4-03'),`No; exporting would reduce profit by $${(140000+50000-180000).toLocaleString('en-US')}.`);
 assert.equal(key('4-05'),`It rises from ${.75*2+.25*6} to ${.5*2+.5*6} solely through reallocation.`);
 assert.equal(key('4-07'),`$${5/(5-1)*24}.`);
 assert.ok(Math.abs(1-Math.abs(80-60)/(80+60)-6/7)<1e-12);
 assert.equal(key('5-01'),`$${10+3}.`);
 assert.equal(key('5-02'),`${100-2*(10+5)-(10+10+5)} units.`);
 assert.equal(key('5-03'),`$${.5*4*(6+10)}.`);
 assert.equal(key('5-04'),`$${40*(15-10)}.`);
 assert.equal(key('5-08'),`${100*((110-66)-(100-60))/(100-60)}%.`);
 assert.equal(key('6-01'),`${Math.round((1.2*1.1-1)*100)}%.`);
 assert.ok(Math.abs(1.1**-1.2-.892)<.0005);
 assert.equal(key('6-05'),`$${200-120}.`);
 assert.equal(key('6-06'),`${(20000/(9-5)).toLocaleString('en-US')} units.`);
});
